"""BERT learning-rate sweep, selected on the validation split.

The fixed 1e-5 in the configs was assumed, never tested. This runs a small shared LR
sweep over a size-spanning subset of organisms and picks the LR by validation R2, so the
choice is a measured one. It is deliberately NOT a per-organism grid: LR is the dominant
fine-tuning knob, one shared value keeps the protocol symmetric with the pending ESM sweep.

This TRAINS models, so it needs a GPU. Intended to run on Kaggle or the cluster, not on the
dev machine. From the repo root:

    python results/lr_sweep_bert.py

Reads nothing but the random-split configs and data already in the repo. Writes a table to
results/lr_sweep_bert.md. Runs land under bert_plots/ with an lr-tagged suffix, so they never
touch the real `bert` sweep outputs or their metrics.json.

Edit DATASETS / LRS below to widen or narrow the sweep. Edge-of-grid rule: if the winning LR
sits at the lowest or highest value tried, extend the grid in that direction and re-run,
otherwise you have only found the best of a truncated range.
"""
import sys
import statistics as st
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

# Config basenames under src/modeling/configs/random_split/ (without .yaml). Chosen to span
# the dataset-size range: large, medium, small. Drop e_coli first if Kaggle time is tight.
DATASETS = ["e_coli", "a_baumannii", "enterobacter"]
LRS = [1e-5, 3e-5, 5e-5]

CONFIG_DIR = REPO_ROOT / "src" / "modeling" / "configs" / "random_split"
OUT = REPO_ROOT / "results" / "lr_sweep_bert.md"


def _tag(lr):
    return f"bert_lr{lr:.0e}"  # 1e-5 -> "bert_lr1e-05", collision-free output suffix


def run_sweep():
    from src.modeling.fine_tune import fine_tune

    results = {ds: {} for ds in DATASETS}
    for ds in DATASETS:
        config_path = CONFIG_DIR / f"{ds}.yaml"
        if not config_path.exists():
            print(f"[skip] no config for {ds} at {config_path}")
            continue
        for lr in LRS:
            print(f"\n=== {ds}  lr={lr:.0e} ===", flush=True)
            try:
                stats = fine_tune(
                    config_path=str(config_path),
                    overrides={"model_name": _tag(lr), "learning_rate": lr},
                )
                val_r2, val_mse = stats["Validation"]
                test_r2, _ = stats["Test"]
                results[ds][lr] = {"val_r2": val_r2, "val_mse": val_mse, "test_r2": test_r2}
                print(f"    val R2={val_r2:.4f}  test R2={test_r2:.4f}")
            except Exception as e:  # keep the sweep alive if one run fails
                results[ds][lr] = None
                print(f"    FAILED: {e}")
    return results


def _cell(entry, key):
    return f"{entry[key]:.3f}" if entry else "—"


def _best_lr(row):
    ok = {lr: e["val_r2"] for lr, e in row.items() if e}
    return max(ok, key=ok.get) if ok else None


def render(results):
    head = "| Organism | " + " | ".join(f"lr={lr:.0e}" for lr in LRS) + " | best (val) |"
    sep = "|" + "---|" * (len(LRS) + 2)

    val_tbl = [head, sep]
    for ds in DATASETS:
        row = results.get(ds, {})
        cells = [_cell(row.get(lr), "val_r2") for lr in LRS]
        best = _best_lr(row)
        val_tbl.append(f"| {ds} | " + " | ".join(cells) + f" | {best:.0e} |" if best
                       else f"| {ds} | " + " | ".join(cells) + " | — |")

    test_tbl = ["| Organism | " + " | ".join(f"lr={lr:.0e}" for lr in LRS) + " |",
                "|" + "---|" * (len(LRS) + 1)]
    for ds in DATASETS:
        row = results.get(ds, {})
        cells = [_cell(row.get(lr), "test_r2") for lr in LRS]
        test_tbl.append(f"| {ds} | " + " | ".join(cells) + " |")

    # Mean validation R2 per LR across the datasets that produced a value, to suggest a
    # single shared LR. Only LRs with a value for every dataset are averaged.
    mean_rows = ["| lr | mean val R² | n datasets |", "|---|---|---|"]
    per_lr_mean = {}
    for lr in LRS:
        vals = [results[ds][lr]["val_r2"] for ds in DATASETS
                if results.get(ds, {}).get(lr)]
        if vals:
            per_lr_mean[lr] = st.mean(vals)
            mean_rows.append(f"| {lr:.0e} | {st.mean(vals):.3f} | {len(vals)} |")
    suggested = max(per_lr_mean, key=per_lr_mean.get) if per_lr_mean else None
    sug_txt = (f"Suggested shared LR by mean validation R²: **{suggested:.0e}**. "
               f"If this is at the edge of the swept range, extend the grid and re-run."
               if suggested else "No completed runs to summarise.")

    doc = (
        "<!-- Generated by results/lr_sweep_bert.py. Selection metric: validation R². -->\n\n"
        "# BERT learning-rate sweep\n\n"
        "Shared LR sweep over a size-spanning organism subset, one seed, random split. The LR "
        "is selected on the **validation** split, the test column is shown for reference only "
        "and must not drive the choice.\n\n"
        "## Validation R² (selection metric, higher is better)\n\n"
        + "\n".join(val_tbl) + "\n\n"
        "## Test R² (reference only, not used for selection)\n\n"
        + "\n".join(test_tbl) + "\n\n"
        "## Shared-LR summary\n\n"
        + "\n".join(mean_rows) + "\n\n" + sug_txt + "\n"
    )
    OUT.write_text(doc, encoding="utf-8", newline="\n")
    print(f"\nwrote {OUT}")
    print(sug_txt)


if __name__ == "__main__":
    render(run_sweep())
